export function generateCandles(basePrice: number, count = 30): CandleData[] {
  const candles: CandleData[] = [];
  let currentPrice = basePrice * 0.97;
  const now = Date.now();

  for (let i = 0; i < count; i++) {
    const timeDelta = (count - i) * 60 * 1000 * 5; // 5-minute bars
    const timeStr = new Date(now - timeDelta).toLocaleTimeString([], {
      hour: '2-digit',
      minute: '2-digit',
    });
    const volatility = currentPrice * 0.008;
    const change = (Math.random() - 0.48) * volatility;
    const open = currentPrice;
    const close = +(open + change).toFixed(2);
    const high = +(Math.max(open, close) + Math.random() * volatility * 0.7).toFixed(2);
    const low = +(Math.min(open, close) - Math.random() * volatility * 0.7).toFixed(2);
    const volume = Math.floor(10000 + Math.random() * 85000);

    candles.push({
      time: timeStr,
      open,
      high,
      low,
      close,
      volume,
    });
    currentPrice = close;
  }
  return candles;
}
